USER_AGENT = "ISL-INCLUDE50-Selective-Reference-Downloader/1.0"
VIDEO_EXTENSIONS = {".mov", ".mp4", ".avi", ".m4v", ".webm"}
SPLIT_PRIORITY = {"train": 0, "val": 1, "validation": 1, "test": 2}
MAX_RANGE_BYTES = 128 * 1024 * 1024
