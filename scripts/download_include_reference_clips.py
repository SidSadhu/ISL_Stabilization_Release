class RangeNotSupported(RuntimeError):
    """Raised when a server ignores or corrupts an HTTP Range request."""


class HTTPRangeReader:
    """Minimal seekable read-only file object backed by exact HTTP Range requests."""

    def __init__(self, url: str, size: int, timeout: int = 60, retries: int = 3):
        self.url = url
        self.size = int(size)
        self.timeout = timeout
        self.retries = retries
        self.position = 0
        self.closed = False

    def seekable(self) -> bool:
        return True

    def readable(self) -> bool:
        return True

    def tell(self) -> int:
        return self.position

    def seek(self, offset: int, whence: int = io.SEEK_SET) -> int:
        if whence == io.SEEK_SET:
            target = offset
        elif whence == io.SEEK_CUR:
            target = self.position + offset
        elif whence == io.SEEK_END:
            target = self.size + offset
        else:
            raise ValueError(f"Invalid whence: {whence}")
        if target < 0:
            raise ValueError("Negative seek position")
        self.position = min(int(target), self.size)
        return self.position

    def read(self, size: int = -1) -> bytes:
        if self.closed:
            raise ValueError("I/O operation on closed range reader")
        if self.position >= self.size:
            return b""
        if size is None or size < 0:
            size = self.size - self.position
        size = min(int(size), self.size - self.position)
        if size == 0:
            return b""
        if size > MAX_RANGE_BYTES:
            raise RangeNotSupported(
                f"Refusing oversized range read ({size:,} bytes); archive server/library requested too much data."
            )

        start = self.position
        end = start + size - 1
        last_error: Exception | None = None
        for attempt in range(self.retries):
            request = Request(
                self.url,
                headers={"Range": f"bytes={start}-{end}", "User-Agent": USER_AGENT},
            )
            try:
                with urlopen(request, timeout=self.timeout) as response:
                    status = getattr(response, "status", response.getcode())
                    content_range = response.headers.get("Content-Range", "")
                    match = re.fullmatch(r"bytes\s+(\d+)-(\d+)/(\d+|\*)", content_range.strip(), re.I)
                    if status != 206 or not match:
                        raise RangeNotSupported(
                            f"Server did not honour byte range {start}-{end} (HTTP {status}, Content-Range={content_range!r})."
                        )
                    returned_start, returned_end = int(match.group(1)), int(match.group(2))
                    if returned_start != start or returned_end != end:
                        raise RangeNotSupported(
                            f"Server returned a different byte range: {content_range!r}; expected {start}-{end}."
                        )
                    payload = response.read()
                    if len(payload) != size:
                        raise RangeNotSupported(
                            f"Incomplete ranged response: received {len(payload)} of {size} requested bytes."
                        )
                    self.position += len(payload)
                    return payload
            except RangeNotSupported:
                raise
            except (HTTPError, URLError, TimeoutError, OSError, IncompleteRead) as exc:
                last_error = exc
                if attempt + 1 < self.retries:
                    time.sleep(0.75 * (2 ** attempt))
        raise RuntimeError(f"Range request failed after {self.retries} attempts: {last_error}")

    def close(self) -> None:
        self.closed = True

    def __enter__(self) -> "HTTPRangeReader":
        return self

    def __exit__(self, *_: object) -> None:
        self.close()


ALIASES = {
    "biglarge": {"biglarge", "big large", "large"},
    "cellphone": {"cellphone", "cell phone", "mobile phone"},
    "goodmorning": {"goodmorning", "good morning"},
    "smalllittle": {"smalllittle", "small little", "small", "little"},
    "storeorshop": {"storeorshop", "store or shop", "store", "shop"},
    "trainticket": {"trainticket", "train ticket"},
    "tshirt": {"tshirt", "t shirt", "t-shirt"},
    "youplural": {"youplural", "you plural", "you (plural)"},
    "thankyou": {"thankyou", "thank you"},
    "i": {"i", "me"},
}


def normalize_text(value: str) -> str:
    return "".join(ch.lower() for ch in str(value) if ch.isalnum())


def canonical_label(raw_label: str, valid_labels: set[str]) -> str | None:
    class_name = str(raw_label).replace("\\", "/").split("/")[-1]
    class_name = re.sub(r"^\s*\d+\s*[.\-_:]?\s*", "", class_name).strip()
    normalized = normalize_text(class_name)
    for label in valid_labels:
        forms = {normalize_text(label)} | {normalize_text(alias) for alias in ALIASES.get(label, set())}
        if normalized in forms:
            return label
    return None


def local_video_path(destination: Path, row: dict[str, Any]) -> Path:
    try:
        return resolve_manifest_video(destination, row["video_path"])
    except (ValueError, RuntimeError) as exc:
        raise ValueError(f"Unsafe or ambiguous metadata path: {row['video_path']}: {exc}") from exc


def select_rows(rows: list[dict[str, Any]], destination: Path, profile: str) -> list[dict[str, Any]]:
    by_label: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_label[row["model_label"]].append(row)
    selected: list[dict[str, Any]] = []

    if profile == "coverage":
        # Existing local coverage is preserved. Only a class with no local reference
        # receives one new train sample (fallback to val/test only if no train row exists).
        for label in sorted(by_label):
            items = sorted(by_label[label], key=lambda r: (SPLIT_PRIORITY.get(r["split"], 9), r["video_path"].casefold()))
            if any(local_video_path(destination, row).is_file() for row in items):
                continue
            available = [r for r in items if r["split"] == "train"]
            if not available:
                available = [r for r in items if r["split"] == "val"] or [r for r in items if r["split"] == "test"]
            if available:
                selected.append(available[0])
    elif profile == "validation-all":
        # Select every missing official validation row supplied by the pinned path-list
        # parser. Never include train or test items in this profile.
        for label in sorted(by_label):
            for row in sorted(by_label[label], key=lambda r: r["video_path"].casefold()):
                if row["split"] != "val":
                    continue
                if not local_video_path(destination, row).is_file():
                    selected.append(row)
    else:
        raise ValueError(f"Unknown profile: {profile}")

    # Deduplicate by metadata path and return in stable class/split order.
    unique: dict[str, dict[str, Any]] = {}
    for row in selected:
        unique[row["video_path"].casefold()] = row
    return sorted(unique.values(), key=lambda r: (r["model_label"], SPLIT_PRIORITY.get(r["split"], 9), r["video_path"].casefold()))


def fetch_zenodo_archives() -> list[dict[str, Any]]:
    request = Request(ZENODO_RECORD_API, headers={"User-Agent": USER_AGENT})
    with urlopen(request, timeout=60) as response:
        record = json.loads(response.read().decode("utf-8"))
    archives = []
    for item in record.get("files", []):
        key = str(item.get("key", ""))
        links = item.get("links", {}) or {}
        url = links.get("self") or links.get("download")
        size = int(item.get("size", 0) or 0)
        if key.lower().endswith(".zip") and url and size > 0:
            archives.append({"key": key, "url": url, "size": size})
    if not archives:
        raise RuntimeError("The official Zenodo record returned no ZIP archives.")
    return archives


def normalize_archive_path(value: str) -> str:
    text = str(value).replace("\\", "/").lstrip("./")
    while "//" in text:
        text = text.replace("//", "/")
    return text.casefold()


def archive_path_identity(value: str) -> str:
    """Case-insensitive archive path identity without its video extension."""
    path = PurePosixPath(normalize_archive_path(value))
    return str(path.with_suffix("")).casefold()


def archive_member_target_path(official_path: str, member_name: str) -> str:
    """Return official manifest directory/stem with the archive's real suffix."""
    expected = PurePosixPath(str(official_path).replace("\\", "/"))
    member = PurePosixPath(str(member_name).replace("\\", "/"))
    if expected.is_absolute() or ".." in expected.parts or (expected.parts and ":" in expected.parts[0]):
        raise ValueError(f"Unsafe official manifest path: {official_path}")
    if member.is_absolute() or ".." in member.parts or (member.parts and ":" in member.parts[0]):
        raise ValueError(f"Unsafe ZIP member path: {member_name}")
    if member.suffix.lower() not in VIDEO_EXTENSIONS:
        raise ValueError(f"ZIP member is not a supported video file: {member_name}")
    expected_identity = archive_path_identity(str(expected))
    member_identity = archive_path_identity(str(member))
    if member_identity != expected_identity and not member_identity.endswith("/" + expected_identity):
        raise ValueError(
            f"ZIP member does not match official manifest video identity: "
            f"{member_name} != {official_path}"
        )
    return str(expected.with_suffix(member.suffix))


def index_remote_archives(archives: list[dict[str, Any]], wanted_paths: set[str]) -> dict[str, tuple[dict[str, Any], str]]:
    """Index exact paths first, then allow a same-path .MOV/.MP4 suffix variant.

    The upstream official validation list contains some .MOV paths whose exact
    video IDs are published in Zenodo ZIPs as .MP4. Matching is restricted to
    the identical parent directory and stem; arbitrary class/sample substitution
    is never permitted. Exact extension matches always take precedence.
    """
    wanted_exact = {normalize_archive_path(path): path for path in wanted_paths}
    identity_to_wanted: dict[str, str] = {}
    for normalized, original in wanted_exact.items():
        identity = archive_path_identity(normalized)
        if identity in identity_to_wanted and identity_to_wanted[identity] != normalized:
            raise ValueError(f"Ambiguous requested video paths share the same stem: {original}")
        identity_to_wanted[identity] = normalized

    exact_candidates: dict[str, list[tuple[dict[str, Any], str]]] = {p: [] for p in wanted_exact}
    extension_candidates: dict[str, list[tuple[dict[str, Any], str]]] = {p: [] for p in wanted_exact}

    for archive in archives:
        print(f"  Inspecting ZIP index only: {archive['key']} ({archive['size'] / (1024**3):.2f} GiB)")
        try:
            with HTTPRangeReader(archive["url"], archive["size"]) as remote:
                with zipfile.ZipFile(remote, "r") as zf:
                    for name in zf.namelist():
                        normalized = normalize_archive_path(name)
                        if not normalized or normalized.endswith("/"):
                            continue
                        # Exact full path match (including extension) has priority.
                        for wanted in wanted_exact:
                            if normalized == wanted or normalized.endswith("/" + wanted):
                                exact_candidates[wanted].append((archive, name))
                                break
                        else:
                            member_path = PurePosixPath(normalized)
                            if member_path.suffix.lower() not in VIDEO_EXTENSIONS:
                                continue
                            identity = archive_path_identity(normalized)
                            wanted = identity_to_wanted.get(identity)
                            if wanted and member_path.suffix.lower() != PurePosixPath(wanted).suffix.lower():
                                extension_candidates[wanted].append((archive, name))
        except (RangeNotSupported, zipfile.BadZipFile, OSError, RuntimeError) as exc:
            print(f"  WARNING: could not index {archive['key']}: {type(exc).__name__}: {exc}", file=sys.stderr)
            # A failed Range request is fail-closed: no full-archive download fallback.
            if isinstance(exc, RangeNotSupported):
                raise

    found: dict[str, tuple[dict[str, Any], str]] = {}
    for wanted in wanted_exact:
        candidates = exact_candidates[wanted] or extension_candidates[wanted]
        # De-duplicate exact repeated index records, but never choose between
        # multiple distinct archive members with the same official video ID.
        unique = {(item[0]["key"], item[1]): item for item in candidates}
        if len(unique) == 1:
            found[wanted] = next(iter(unique.values()))
        elif len(unique) > 1:
            choices = ", ".join(f"{archive_key}:{member}" for archive_key, member in sorted(unique))
            raise RuntimeError(f"Ambiguous remote archive members for {wanted}: {choices}")
    print(f"  Located {len(found)}/{len(wanted_paths)} requested video IDs")
    return found


def download_member(archive: dict[str, Any], member_name: str, destination: Path, relative_path: str) -> int:
    target = destination.joinpath(*PurePosixPath(relative_path).parts).resolve()
    target.relative_to(destination.resolve())
    if target.is_file():
        return target.stat().st_size
    with HTTPRangeReader(archive["url"], archive["size"]) as remote:
        with zipfile.ZipFile(remote, "r") as zf:
            try:
                info = zf.getinfo(member_name)
            except KeyError as exc:
                raise RuntimeError(f"Archive member disappeared during download: {member_name}") from exc
            if info.is_dir() or info.file_size <= 0:
                raise RuntimeError(f"Invalid empty/directory video member: {member_name}")
            contents = zf.read(info)
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_name(target.name + ".part")
    temp.write_bytes(contents)
    temp.replace(target)
    return target.stat().st_size


def write_manifest(rows: list[dict[str, Any]], destination: Path, project_root: Path) -> Path:
    manifest = project_root / "outputs" / "include50_local_manifest.csv"
    manifest.parent.mkdir(parents=True, exist_ok=True)
    columns = ["video_path", "label", "split", "parent_label"]
    with manifest.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        for row in rows:
            if local_video_path(destination, row).is_file():
                writer.writerow({
                    "video_path": row["video_path"],
                    "label": row["model_label"],
                    "split": row["split"],
                    "parent_label": row.get("parent_label", ""),
                })
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", choices=("coverage", "validation-all"), default="coverage")
    parser.add_argument("--ai4bharat-repo", type=Path, default=Path(os.getenv("AI4BHARAT_REPO", "")) if os.getenv("AI4BHARAT_REPO") else None,
                        help="Required for validation-all; pinned official AI4Bharat repository")
    parser.add_argument("--metadata", type=Path, default=Path("data/include50_video_metadata.json"))
    parser.add_argument("--destination", type=Path, default=Path(r"C:\AIAssets\INCLUDE_videos"))
    parser.add_argument("--label-map", type=Path, default=Path("config/label_map_include50.json"))
    parser.add_argument("--download", action="store_true", help="Actually download selected video members; default is preview only")
    args = parser.parse_args()

    try:
        label_map = json.loads(args.label_map.read_text(encoding="utf-8"))
        valid_labels = set(label_map)
        if len(valid_labels) != 50:
            raise ValueError(f"Expected 50 official labels in {args.label_map}, found {len(valid_labels)}")
        destination = args.destination.expanduser().resolve()
        project_root = Path.cwd()

        if args.profile == "validation-all":
            if args.ai4bharat_repo is None:
                raise ValueError("--profile validation-all requires --ai4bharat-repo or AI4BHARAT_REPO.")
            rows, commit, digest = load_official_validation_rows(args.ai4bharat_repo, valid_labels)
            selected = [row for row in rows if not local_video_path(destination, {**row, "model_label": row["label"]}).is_file()]
            represented = {row["label"] for row in rows}
            locally_present = {row["label"] for row in rows if local_video_path(destination, {**row, "model_label": row["label"]}).is_file()}
            print("INCLUDE-50 official validation split — source-verified mode")
            print(f"Official path-list entries: {len(rows)} | Represented classes: {len(represented)}/50")
            print(f"Pinned repository commit: {commit}")
            print(f"Path-list SHA256: {digest}")
            print(f"Local validation clips present: {sum(local_video_path(destination, {**r, 'model_label': r['label']}).is_file() for r in rows)}/77")
            print(f"Selected new validation clips: {len(selected)}")
        else:
            payload = json.loads(args.metadata.read_text(encoding="utf-8"))
            raw_rows = payload.get("videos", [])
            rows: list[dict[str, Any]] = []
            seen: set[str] = set()
            for row in raw_rows:
                if not isinstance(row, dict):
                    continue
                source_flag = row.get("include_50") is True
                model_match_flag = row.get("model_class_match") is True
                if not source_flag and not model_match_flag:
                    continue
                rel = str(row.get("video_path", "")).replace("\\", "/").lstrip("/")
                if not rel or ".." in PurePosixPath(rel).parts or PurePosixPath(rel).suffix.lower() not in VIDEO_EXTENSIONS:
                    continue
                label = str(row.get("matched_model_label", "")).strip() or canonical_label(str(row.get("label", "")), valid_labels)
                if label not in valid_labels:
                    continue
                split = str(row.get("split", "unknown")).lower().strip()
                if split == "validation":
                    split = "val"
                if split not in {"train", "val", "test"}:
                    continue
                key = rel.casefold()
                if key in seen:
                    continue
                seen.add(key)
                rows.append({**row, "video_path": rel, "model_label": label, "split": split})
            if not rows:
                raise ValueError("No valid INCLUDE-50 rows with train/val/test split metadata were found. Re-run prepare_include_references.py.")
            selected = select_rows(rows, destination, args.profile)
            represented = {row["model_label"] for row in rows}
            locally_present = {row["model_label"] for row in rows if local_video_path(destination, row).is_file()}
            print(f"INCLUDE-50 split-aware selective download — profile: {args.profile}")
            print(f"Metadata entries: {len(rows)} | Classes represented in metadata: {len(represented)}/50")
            print(f"Current local coverage: {len(locally_present)}/50 classes | Local clips: {sum(local_video_path(destination, r).is_file() for r in rows)}")
            missing_metadata_labels = sorted(valid_labels - represented)
            if missing_metadata_labels:
                print("WARNING: no INCLUDE-50 metadata rows were found for: " + ", ".join(missing_metadata_labels), file=sys.stderr)
            print(f"Selected new clips: {len(selected)}")

        if not selected:
            print("Nothing to download; the requested validation coverage is already present.")
        for row in selected:
            label = row.get("model_label", row.get("label", ""))
            print(f"  {label:14s} [{row['split']:5s}] {row['video_path']}")

        if args.download and selected:
            print("\nOnly selected video members will be fetched using HTTP byte ranges. ZIP archives will NOT be saved locally.")
            answer = input("Type FETCH CLIPS to continue: ").strip()
            if answer != "FETCH CLIPS":
                print("Cancelled; no video bytes downloaded.")
                return 0
            archives = fetch_zenodo_archives()
            wanted = {normalize_archive_path(row["video_path"]) for row in selected}
            print(f"\nSearching {len(archives)} official ZIP central directories using HTTP Range requests...")
            member_map = index_remote_archives(archives, wanted)
            missing = wanted - set(member_map)
            if missing:
                print("WARNING: These official split paths were not found in the remote ZIP indexes:", file=sys.stderr)
                for path in sorted(missing):
                    print(f"  {path}", file=sys.stderr)
            downloaded = 0
            for row in selected:
                key = normalize_archive_path(row["video_path"])
                if key not in member_map:
                    continue
                archive, member_name = member_map[key]
                # Save using the actual archive member path and suffix (.MP4/.MOV),
                # never relabel the media container by changing its extension.
                local_relative_path = archive_member_target_path(row["video_path"], member_name)
                size = download_member(archive, member_name, destination, local_relative_path)
                downloaded += 1
                label = row.get("model_label", row.get("label", ""))
                print(
                    f"Downloaded {label} [{row['split']}]: {size:,} bytes "
                    f"({member_name} -> {local_relative_path})"
                )
            report_dir = project_root / "outputs"
            report_dir.mkdir(parents=True, exist_ok=True)
            report = {
                "created_at_utc": datetime.now(timezone.utc).isoformat(),
                "dataset": "ai4bharat/INCLUDE",
                "profile": args.profile,
                "destination": str(destination),
                "selected_count": len(selected),
                "downloaded_count": downloaded,
                "missing_archive_members": sorted(missing),
                "selected": [{k: row.get(k, row.get("label") if k == "model_label" else None) for k in ("model_label", "split", "video_path", "label", "parent_label")} for row in selected],
                "resolved_archive_members": [
                    {
                        "official_manifest_path": row["video_path"],
                        "archive_member": member_map[normalize_archive_path(row["video_path"])][1],
                        "local_path": archive_member_target_path(
                            row["video_path"], member_map[normalize_archive_path(row["video_path"])][1]
                        ),
                    }
                    for row in selected if normalize_archive_path(row["video_path"]) in member_map
                ],
                "bulk_archives_downloaded": False,
            }
            (report_dir / "include50_reference_download_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
            print(f"\nFinished: {downloaded}/{len(selected)} selected video(s) downloaded.")

        if args.profile == "validation-all":
            manifest = project_root / "outputs" / "include50_official_val_manifest.csv"
            write_official_val_manifest(rows, manifest)
            print(f"Official 77-item validation manifest: {manifest}")
        else:
            manifest = write_manifest(rows, destination, project_root)
            print(f"Local INCLUDE-50 manifest: {manifest}")
        print("Use this official validation split for evaluation/threshold analysis. Keep test videos locked until all choices are frozen.")
        return 0
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
