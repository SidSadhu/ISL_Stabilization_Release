#!/usr/bin/env python3
"""Download a small, split-aware subset of official INCLUDE-50 videos.

The script reads the local metadata index generated by prepare_include_references.py,
then uses HTTP Range requests against the official Zenodo ZIP files. It downloads only
selected video members; it never downloads the complete ZIP archives.

Profiles:
  coverage        Add one TRAIN reference video for each class that has no local clip.
  validation-all  Fetch only the exact 77 items in the pinned official INCLUDE-50 validation list.

Run without --download to preview the selection. A typed confirmation is required to
transfer video bytes. Existing files are skipped and never overwritten.
"""
